def extract(s,n):
 p=list(re.finditer(r'^(?:static )?(?:int32|int|void|x_base)\s+'+re.escape(n)+r'\s*\([^;]*?\)\s*\{',s,re.M))[-1]
 start=p.start(); b=p.end(); depth=1; quote=None; i=b
 while depth:
  if s.startswith('//',i) and quote is None:
   i=s.index('\n',i);continue
  if s.startswith('/*',i) and quote is None:
   i=s.index('*/',i)+2;continue
  c=s[i]
  if quote:
   if c=='\\':i+=2;continue
   if c==quote:quote=None
  elif c in '\"\'':quote=c
  elif c=='{':depth+=1
  elif c=='}':depth-=1
  i+=1
 return start,s[start:i]
